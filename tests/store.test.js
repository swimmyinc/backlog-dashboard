import test, { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Miniflare, convertV4MiniflareOptions } from 'miniflare';
import { createStore } from '../store.js';
import { createWorker } from '../worker.js';
let mf, db, store;
before(async () => {
  mf = new Miniflare(convertV4MiniflareOptions({ workers: [{ name: 'test', modules: true, script: 'export default { fetch() { return new Response("ok"); } }', d1Databases: ['DB'] }] }));
  db = await mf.getD1Database('DB');
  const sql = await readFile(new URL('../migrations/0001_initial.sql', import.meta.url), 'utf8');
  await db.batch(sql.split(';').filter(s => s.trim()).map(s => db.prepare(s)));
  store = createStore(db);
});
after(async () => { await mf?.dispose(); });
const settings = { name: '顧客', director: '', projectId: '123', spaceUrl: 'https://example.backlog.com', monthlyHours: 100, carryOverHours: 0, extraHours: 0, synced: false, data: null };
const data = { completed: [], inProgress: [], notStarted: [] };
const snapshot = { from: '2026-08-01', to: '2026-08-31', capacity: 100, est: 0, act: 0, remaining: 100, data };
test('共有保存・同一期間の更新・競合・変更時削除・削除連鎖を実D1で検証する', async () => {
  const c = await store.add(settings);
  await assert.rejects(store.add(settings), e => e.status === 409);
  const updated = await store.update(c.id, c.revision, { ...settings, data }, { snapshot });
  assert.equal(updated.revision, 2);
  assert.equal(updated.history.length, 1);
  await assert.rejects(store.update(c.id, c.revision, { ...settings, name: '古い変更' }, { snapshot: { ...snapshot, from: '2026-07-01' } }), e => e.status === 409);
  assert.equal((await store.get(c.id)).history.length, 1);
  const again = await store.update(c.id, updated.revision, settings, { snapshot: { ...snapshot, capacity: 200 } });
  assert.equal(again.history.length, 1);
  assert.equal(again.history[0].id, updated.history[0].id);
  assert.equal((await store.history(c.id, again.history[0].id)).capacity, 200);
  await assert.rejects(store.history('different-client', again.history[0].id), e => e.status === 404);
  const changed = await store.update(c.id, again.revision, { ...settings, projectId: '456' }, { clearHistory: true });
  assert.equal(changed.history.length, 0);
  const last = await store.update(c.id, changed.revision, settings, { snapshot });
  await assert.rejects(store.remove(c.id, changed.revision), e => e.status === 409);
  await store.remove(c.id, last.revision);
  assert.equal((await db.prepare('SELECT count(*) AS n FROM history').first()).n, 0);
});
test('同時更新は一件だけ成功し、容量超過は元データを保持する', async () => {
  const c = await store.add({ ...settings, projectId: '789' });
  const outcomes = await Promise.allSettled([1, 2].map(n => store.update(c.id, c.revision, { ...settings, projectId: '789', name: String(n) }, { snapshot })));
  assert.equal(outcomes.filter(r => r.status === 'fulfilled').length, 1);
  assert.equal(outcomes.find(r => r.status === 'rejected').reason.status, 409);
  const saved = await store.get(c.id);
  await assert.rejects(store.update(c.id, saved.revision, { ...settings, data: 'あ'.repeat(400000) }), e => e.status === 422);
  assert.equal((await store.get(c.id)).revision, saved.revision);
});
test('一般利用者は閲覧・取得のみ、管理者はプロジェクトを検証して登録する', async () => {
  const env = { DB: db, LOCAL_DEV: 'true', LOCAL_USER_EMAIL: 'member@example.test', ADMIN_EMAILS: 'admin@example.test', BACKLOG_SPACE_URL: settings.spaceUrl, BACKLOG_API_KEY: 'secret' };
  let calls = 0;
  const worker = createWorker({ fetchImpl: async url => { calls++; return Response.json(url.pathname.endsWith('/statuses') || url.pathname.endsWith('/issueTypes') ? [] : { id: 999 }); } });
  const req = (path, method = 'GET', body) => new Request('http://localhost' + path, { method, headers: { 'Content-Type': 'application/json', 'Cf-Access-Authenticated-User-Email': 'admin@example.test' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const body = { name: '新規', director: '', projectId: 'TEST', monthlyHours: 100, carryOverHours: 0, extraHours: 0 };
  for (const [path, method] of [['/api/clients', 'POST'], ['/api/clients/unknown', 'PUT'], ['/api/clients/unknown', 'DELETE']]) assert.equal((await worker.fetch(req(path, method, body), env)).status, 403);
  assert.equal(calls, 0);
  assert.equal((await worker.fetch(req('/api/clients'), env)).status, 200);
  const response = await worker.fetch(req('/api/clients', 'POST', body), { ...env, LOCAL_USER_EMAIL: 'ADMIN@example.test' });
  assert.equal(response.status, 201);
  const client = await response.json();
  assert.equal(client.projectId, '999');
  const fetched = await worker.fetch(req('/api/clients/' + client.id + '/fetch', 'POST', { revision: client.revision, from: '2026-08-01', to: '2026-08-31' }), env);
  assert.equal(fetched.status, 200);
  assert.equal((await fetched.json()).history[0].fetchedBy, 'member@example.test');
  assert.equal((await worker.fetch(req('/api/clients', 'POST', body), { ...env, LOCAL_USER_EMAIL: 'admin@example.test', ADMIN_EMAILS: '' })).status, 403);
});
